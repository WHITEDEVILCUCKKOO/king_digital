<script>
  const firstSection = document.getElementById('first-section');
  const scrollTopBtn = document.getElementById('scrollTopBtn');

  function toggleScrollButton() {
    const rect = firstSection.getBoundingClientRect();

    // If any part of the first section is visible
    if (rect.bottom > 0 && rect.top < window.innerHeight) {
      scrollTopBtn.classList.remove('show');
      scrollTopBtn.classList.add('hide');
    } else {
      scrollTopBtn.classList.remove('hide');
      scrollTopBtn.classList.add('show');
    }
  }

  window.addEventListener('scroll', toggleScrollButton);
  window.addEventListener('load', toggleScrollButton);

  function kdScrollTop() {
    window.scrollTo({
      top: 0,
      behavior: "smooth"
    });
  }

  function kdHandleSubmit() {
    var input = document.querySelector('.kd-newsletter-input');
    if (!input.value || !input.value.includes('@')) {
      input.style.boxShadow = '0 0 0 3px rgba(224,65,58,0.5)';
      input.focus();
      setTimeout(function() {
        input.style.boxShadow = '';
      }, 1200);
      return;
    }
    var btn = document.querySelector('.kd-submit-btn');
    var original = btn.textContent;
    btn.textContent = 'Subscribed ✓';
    input.value = '';
    setTimeout(function() {
      btn.textContent = original;
    }, 1800);
  }
</script>

